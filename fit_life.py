# FitLife - проект приложения фитнес-бота

# 1. Знакомство с пользователем
# Спросить имя пользователя, сохранить как переменную user_name
# Спросить вес пользователя, созранить как переменную user_age
user_name = input('Добро пожаловать! Как я могу к Вам обращаться? ')
user_age = int(input('Укажите, Ваш возраст '))

# 2. Сбор параметров пользователя и расчет показателей
# Запросить вес пользователя (в кг),
# сохранить как переменную user_weight (тип float)
# Запросить рост пользователя (в метрах)
# сохранить как переменную user_height (тип float)
user_weight = float(input('Пожалуйста, введите Ваш вес в кг: '))
user_height = float(input('Введите Ваш рост в метрах (например: 1.75): '))
# Расчет ИМТ пользователя
bmi = user_weight / (user_height ** 2)
bmi = round(bmi, 1)
# Расчет нормы потребления воды мл (перевест в литры)
water_ml = user_weight * 30
water_l = water_ml / 1000

# 3. Вывод результата
print(f'Приветствую Вас {user_name}! Возраст: {user_age} г.')
print(f'Ваш индекс массы тела: {bmi}')
print(f'Рекомендуемая норма воды {water_l:.3f} л. в день')
print('Расчет окончен. Будьте здоровы!')
